const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
function setup(editable=false) {
    const tile=id=>`<div data-dashboard-item data-dashboard-id="${id}" id="${id}"><input name="cards[]" value="${id}"><input data-position value="1"><button type="button" data-drag-handle>Griff</button><button type="button" data-move="up">Hoch</button><button type="button" data-move="down">Runter</button><button type="button" data-dashboard-remove>Entfernen</button></div>`;
    const items=['a','b','c'].map(tile).join('');
    const dom=new JSDOM(`<form action="/dashboard/preferences" data-dashboard-form ${editable?'data-dashboard-editable':''}><input name="version" value="0"><button type="button" data-dashboard-edit>Bearbeiten</button><button data-layout-save>Speichern</button><div data-dashboard-list data-dashboard-group="cards">${items}</div><p data-dashboard-empty="cards" hidden>Leer</p>${['a','b','c'].map(id=>`<button type="button" data-dashboard-add="${id}" data-dashboard-group="cards" hidden>Hinzufügen</button><template data-dashboard-template="cards:${id}">${tile(id)}</template>`).join('')}<span data-dashboard-status></span></form>`,{url:'https://verein.example.org',runScripts:'outside-only'});
    const {window}=dom;
    require('./browser-texts.cjs')(window); window.eval(fs.readFileSync(__dirname+'/../public/assets/home-dashboard.js','utf8'));
    const order=()=>Array.from(window.document.querySelector('[data-dashboard-list]').children).map(item=>item.id);
    const pointer=(target,type,props={})=>{const e=new window.Event(type,{bubbles:true,cancelable:true});Object.assign(e,{pointerId:1,button:0,clientX:0,clientY:0},props);target.dispatchEvent(e);};
    return {window,document:window.document,order,pointer};
}
test('keyboard controls reorder and update non-JS position inputs',()=>{
    const {window,document,order}=setup();
    document.querySelector('#b [data-move="up"]').click();
    assert.deepEqual(order(),['b','a','c']);
    assert.equal(document.querySelector('#b [data-position]').value,'1');
    document.querySelector('#b [data-move="down"]').click();
    assert.deepEqual(order(),['a','b','c']);window.close();
});
test('pointer drag changes order; cancellation restores it',()=>{
    const {window,document,order,pointer}=setup();
    const grip=document.querySelector('#a [data-drag-handle]'),target=document.querySelector('#c');
    target.getBoundingClientRect=()=>({top:100,left:0,width:200,height:100});
    document.elementFromPoint=()=>target;
    pointer(grip,'pointerdown');pointer(grip,'pointermove',{clientY:160});
    assert.deepEqual(order(),['b','c','a']);
    pointer(grip,'pointercancel');assert.deepEqual(order(),['a','b','c']);
    pointer(grip,'pointerdown');pointer(grip,'pointermove',{clientY:160});pointer(grip,'pointerup');
    assert.deepEqual(order(),['b','c','a']);
    assert.equal(document.querySelector('#a [data-position]').value,'3');window.close();
});
test('editing gates drag, reorder, remove and add; saves only on explicit submit',async()=>{
    const {window,document,order,pointer}=setup(true);
    const requests=[];
    window.fetch=(url,options)=>new Promise(resolve=>requests.push({version:options.body.get('version'),cards:options.body.getAll('cards[]'),resolve}));
    const form=document.querySelector('form'),edit=document.querySelector('[data-dashboard-edit]');
    const move=()=>document.querySelector('#a [data-move="down"]').click();
    move();pointer(document.querySelector('#a [data-drag-handle]'),'pointerdown');
    document.querySelector('#a [data-dashboard-remove]').click();
    assert.deepEqual(order(),['a','b','c']);
    assert.equal(document.querySelector('.dashboard-dragging'),null);
    edit.click();move();
    assert.deepEqual(order(),['b','a','c']);assert.equal(requests.length,0);
    document.querySelector('#a [data-dashboard-remove]').click();
    assert.deepEqual(order(),['b','c']);
    document.querySelector('[data-dashboard-add]').click();
    assert.deepEqual(order(),['b','c','a']);
    form.dispatchEvent(new window.Event('submit',{cancelable:true}));
    assert.equal(requests.length,1);assert.deepEqual(requests[0].cards,['b','c','a']);
    move();assert.deepEqual(order(),['b','c','a']);
    requests[0].resolve({ok:true,json:async()=>({version:1})});
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(form.classList.contains('dashboard-editing'),false);
    assert.equal(document.querySelector('[name="version"]').value,'1');
    document.querySelector('#a [data-move="up"]').click();
    assert.deepEqual(order(),['b','c','a']);
    edit.click();form.dispatchEvent(new window.Event('submit',{cancelable:true}));
    assert.equal(requests[1].version,'1');
    requests[1].resolve({ok:false,json:async()=>({error:'Bitte neu laden'})});
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(form.classList.contains('dashboard-editing'),true);
    assert.equal(document.querySelector('[data-dashboard-status]').textContent,'Bitte neu laden');
    window.close();
});

test('empty selection, duplicate additions and network retry preserve the draft',async()=>{
    const {window,document,order}=setup(true);
    const form=document.querySelector('form');
    document.querySelector('[data-dashboard-edit]').click();
    for (const id of ['a','b','c']) document.querySelector('#'+id+' [data-dashboard-remove]').click();
    assert.deepEqual(order(),[]);
    assert.equal(document.querySelector('[data-dashboard-empty]').hidden,false);
    let payload;
    window.fetch=async(url,options)=>{payload=options.body.getAll('cards[]');throw new Error('Offline');};
    form.dispatchEvent(new window.Event('submit',{cancelable:true}));
    await new Promise(resolve=>setImmediate(resolve));
    assert.deepEqual(payload,[]);
    assert.equal(form.classList.contains('dashboard-editing'),true);
    assert.equal(document.querySelector('[data-layout-save]').disabled,false);
    const add=document.querySelector('[data-dashboard-add="a"]');
    add.click();add.click();assert.deepEqual(order(),['a']);
    assert.equal(document.querySelector('[data-dashboard-empty]').hidden,true);
    window.fetch=async()=>({ok:true,json:async()=>({version:1})});
    form.dispatchEvent(new window.Event('submit',{cancelable:true}));
    await new Promise(resolve=>setImmediate(resolve));
    assert.equal(form.classList.contains('dashboard-editing'),false);
    window.close();
});
