CREATE TABLE document_files (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, size integer NOT NULL CHECK(size BETWEEN 1 AND 10485760),
 sha256 text NOT NULL CHECK(sha256 ~ '^[a-f0-9]{64}$')
);
CREATE TABLE document_file_chunks (
 file_id bigint NOT NULL REFERENCES document_files(id), part integer NOT NULL CHECK(part>=0),
 content bytea NOT NULL CHECK(octet_length(content) BETWEEN 1 AND 131072), PRIMARY KEY(file_id,part)
);
CREATE TABLE club_documents (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind text NOT NULL CHECK(kind IN ('minutes','constitution','rules')),
 generation integer NOT NULL DEFAULT 0,
 published_version integer
);
CREATE UNIQUE INDEX club_documents_singleton ON club_documents(kind) WHERE kind <> 'minutes';
CREATE TABLE club_document_versions (
 document_id bigint NOT NULL REFERENCES club_documents(id), version integer NOT NULL,
 title text NOT NULL, label text NOT NULL, document_date date NOT NULL,
 meeting_type text CHECK(meeting_type IN ('board','assembly')),
 participants text NOT NULL DEFAULT '', source text NOT NULL CHECK(source IN ('editor','pdf')),
 content text NOT NULL, file_id bigint REFERENCES document_files(id),
 status text NOT NULL CHECK(status IN ('draft','published')),
 actor_id bigint NOT NULL REFERENCES users(id), created_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(document_id,version),
 CHECK((source='editor' AND file_id IS NULL) OR (source='pdf' AND file_id IS NOT NULL))
);
ALTER TABLE club_documents ADD FOREIGN KEY(id,published_version) REFERENCES club_document_versions(document_id,version) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX club_document_versions_date ON club_document_versions(document_date DESC,document_id DESC);
CREATE FUNCTION reject_document_version_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Document versions and PDF contents are immutable'; END;
$$;
CREATE TRIGGER document_versions_immutable BEFORE UPDATE OR DELETE ON club_document_versions FOR EACH ROW EXECUTE FUNCTION reject_document_version_change();
CREATE TRIGGER document_files_immutable BEFORE UPDATE OR DELETE ON document_files FOR EACH ROW EXECUTE FUNCTION reject_document_version_change();
CREATE TRIGGER document_chunks_immutable BEFORE UPDATE OR DELETE ON document_file_chunks FOR EACH ROW EXECUTE FUNCTION reject_document_version_change();
